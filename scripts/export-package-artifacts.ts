/**
 * Writes the platform-neutral package artifacts next to each other in registry/<id>/:
 * manifest.yaml, schemas/*.json (from the zod schema used at runtime) and SKILL.md.
 *   npm run export:schemas
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';
import { generateSkillMd, JP_TICKET_OPTIMIZER } from '../src/core';
import { jpTicketInputSchema, taskResultSchema } from '../src/core/packages/schema';

const dir = join('registry', JP_TICKET_OPTIMIZER.id);
mkdirSync(join(dir, 'schemas'), { recursive: true });

function toYaml(value: unknown, indent = 0): string {
  const pad = '  '.repeat(indent);
  if (Array.isArray(value)) {
    if (value.length === 0) return ' []';
    if (value.every((v) => typeof v !== 'object' || v === null)) return ` [${value.map(scalar).join(', ')}]`;
    return value.map((v) => `\n${pad}-${toYaml(v, indent + 1).replace(/^\n\s*/, ' ')}`).join('');
  }
  if (value && typeof value === 'object') {
    return Object.entries(value)
      .filter(([, v]) => v !== undefined)
      .map(([k, v]) => `\n${pad}${k}:${typeof v === 'object' && v !== null ? toYaml(v, indent + 1) : ` ${scalar(v)}`}`)
      .join('');
  }
  return ` ${scalar(value)}`;
}

function scalar(v: unknown): string {
  if (typeof v === 'string') return /^[\w.\-/]+$/.test(v) && !/^\d/.test(v) ? v : JSON.stringify(v);
  return String(v);
}

const { compatibility, changelog, ...core } = JP_TICKET_OPTIMIZER;
writeFileSync(
  join(dir, 'manifest.yaml'),
  `# Generated by scripts/export-package-artifacts.ts — source of truth: src/core/packages/registry.ts${toYaml(core)}\ncompatibility:${toYaml(compatibility, 1)}\nchangelog:${toYaml(changelog, 1)}\n`,
);
writeFileSync(
  join(dir, 'schemas', 'jp-ticket-optimizer.input.json'),
  JSON.stringify(z.toJSONSchema(jpTicketInputSchema.omit({ simulation: true }), { target: 'draft-2020-12' }), null, 2) + '\n',
);
writeFileSync(
  join(dir, 'schemas', 'task-result.output.json'),
  JSON.stringify(z.toJSONSchema(taskResultSchema, { target: 'draft-2020-12' }), null, 2) + '\n',
);
writeFileSync(join(dir, 'SKILL.md'), generateSkillMd(JP_TICKET_OPTIMIZER, 'https://<your-lazypack-host>/mcp'));
console.log(`wrote ${dir}/manifest.yaml, schemas/*.json, SKILL.md`);
